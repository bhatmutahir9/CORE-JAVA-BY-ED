package COREJAVA;

public class CommandLineArgs {
    public static void main(String... args) { // we can use (String... args) &(String[] args) also for Variable Args
        System.out.println(args[0]); //Value of these args is passed in the Command Line
        System.out.println(args[1]);
        System.out.println(args[2]);
        System.out.println(args[3]);
        System.out.println(args[4]);
        System.out.println(args[2]);
    }

}
